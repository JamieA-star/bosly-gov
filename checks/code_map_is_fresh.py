#!/usr/bin/env python3
"""The code map is fresh, covers the tree, and saves tokens.

Three assertions, and the first is the one that keeps the map from
rotting:
  - fresh: the stored map's version hash equals the current one; the map
    is regenerated by the read, so a stale map fails the tier;
  - covers: every .py/.ts/.tsx file in the three repos is in the map, or
    the map is regenerated;
  - saves: a code_search answer is shorter than reading the file it
    points to — the number that proves the map is worth it.
"""
import sys

sys.path.insert(0, "/home/bosly_accord/bosly-gov")


def main() -> int:
    print("")
    print("Invariant: the code map is fresh, covers the tree, and saves tokens")
    print("-" * 52)
    ok = True

    try:
        from routers import code_map as cm
    except Exception as e:
        print(f"  FAIL: cannot import code_map: {e}")
        print("SUMMARY: FAIL")
        return 1

    m = cm.load()
    want = cm.version()
    fresh = m.get("version") == want
    print(f"  fresh (version matches the tree): {fresh}")
    ok = ok and fresh

    stored = {mod.get("file") for r in m["repos"].values() for mod in r["modules"]}
    missing = []
    for slug, repo in cm.REPOS.items():
        if not repo.exists():
            continue
        for f in cm._files(repo):
            rel = str(f.relative_to(repo))
            if rel not in stored:
                missing.append(f"{slug}/{rel}")
    print(f"  files missing from the map: {len(missing)}" + (f" {missing[:3]}" if missing else ""))
    ok = ok and not missing

    # A symbol in a known file; the answer must be smaller than the file.
    hit = cm.search("classify_task")
    defined = hit.get("result", {}).get("defined_in") or []
    small = bool(defined)
    if defined:
        import os
        p = cm.GOV / defined[0]["file"]
        file_len = os.path.getsize(p) if p.exists() else 0
        answer_len = len(str(hit))
        small = file_len > 0 and answer_len < file_len
        print(f"  code_search('classify_task') found it in {defined[0]['file']}")
        print(f"  answer {answer_len} bytes vs file {file_len} bytes: {'saves' if small else 'no saving'}")
    else:
        print("  FAIL: code_search('classify_task') found nothing")
    ok = ok and small

    print("")
    print("SUMMARY: " + ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
