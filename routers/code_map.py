"""routers/code_map.py — a map of the codebase, generated from the code.

The butler does not need a language; it needs a map that does not cost
50,000 tokens a turn. The map answers "what is in this module?" in a few
hundred tokens, so read_file is called only for the file being changed.

Generated from the code, never written by the model. Python's ast for
Gov; exports and file names for the TypeScript repos. The map is keyed
on a version hash — every file's path, mtime and size — so it cannot be
served stale: the first read of a changed tree regenerates it.
"""
from __future__ import annotations

import ast
import hashlib
import json
import os
import re
from pathlib import Path
from typing import Any, Dict, List

GOV = Path("/home/bosly_accord/bosly-gov")
REPOS = {
    "bosly-1.0": Path("/home/bosly_accord/bosly-1.0"),
    "bosly-keep": Path("/home/bosly_accord/bosly-keep"),
    "bosly-gov": GOV,
}
MAP_PATH = Path("/mnt/bosly/bosly-data/copilot-knowledge/bosly-gov/code-map.json")
SKIP_DIRS = {".git", "node_modules", ".next", "__pycache__", ".venv", "dist", "build", ".pytest_cache"}
PY_EXT = {".py"}
TS_EXT = {".ts", ".tsx", ".js", ".mjs", ".jsx"}


def _files(repo: Path) -> List[Path]:
    out = []
    for root, dirs, names in os.walk(repo):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for n in names:
            p = Path(root) / n
            if p.suffix in PY_EXT or p.suffix in TS_EXT:
                out.append(p)
    return sorted(out)


def version() -> str:
    """One hash of every file's path, mtime and size, per repo.

    The cache key. It changes when anything changes, and only then, so
    the map is regenerated by the read, not by a schedule.
    """
    h = hashlib.sha1()
    for slug, repo in REPOS.items():
        h.update(slug.encode())
        if not repo.exists():
            continue
        for f in _files(repo):
            try:
                st = f.stat()
            except OSError:
                continue
            h.update(str(f.relative_to(repo)).encode())
            h.update(str(st.st_mtime_ns).encode())
            h.update(str(st.st_size).encode())
    return h.hexdigest()


def _py_module(path: Path, repo: Path) -> Dict[str, Any]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except Exception:
        return {"file": str(path.relative_to(repo)), "error": "parse failed"}
    doc = (ast.get_docstring(tree) or "").split("\n")[0]
    functions, classes, imports = [], [], []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            functions.append(node.name)
        elif isinstance(node, ast.ClassDef):
            classes.append(node.name)
        elif isinstance(node, ast.Import):
            for a in node.names:
                imports.append(a.name)
        elif isinstance(node, ast.ImportFrom):
            if node.module:
                imports.append(node.module)
    return {
        "file": str(path.relative_to(repo)),
        "doc": doc,
        "functions": functions,
        "classes": classes,
        "imports": sorted(set(imports))[:20],
    }


_TS_EXPORT = re.compile(
    r"^export\s+(?:default\s+)?(?:async\s+)?(?:function|const|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)",
    re.MULTILINE,
)


def _ts_module(path: Path, repo: Path) -> Dict[str, Any]:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return {"file": str(path.relative_to(repo)), "error": "read failed"}
    exports = sorted(set(_TS_EXPORT.findall(text)))
    first_comment = ""
    for line in text.splitlines()[:8]:
        s = line.strip()
        if s.startswith("//") or s.startswith("/*") or s.startswith("*"):
            first_comment = s.strip("/* ").strip()
            if first_comment:
                break
    return {"file": str(path.relative_to(repo)), "doc": first_comment, "exports": exports}


def build() -> Dict[str, Any]:
    """Build the whole map and write it. Returns the map."""
    out: Dict[str, Any] = {"version": version(), "repos": {}}
    for slug, repo in REPOS.items():
        mods = []
        if repo.exists():
            for f in _files(repo):
                if f.suffix in PY_EXT:
                    mods.append(_py_module(f, repo))
                else:
                    mods.append(_ts_module(f, repo))
        out["repos"][slug] = {"root": str(repo), "modules": mods}
    MAP_PATH.parent.mkdir(parents=True, exist_ok=True)
    MAP_PATH.write_text(json.dumps(out, indent=2), encoding="utf-8")
    return out


def load() -> Dict[str, Any]:
    """The map, regenerated if the version hash changed."""
    want = version()
    try:
        current = json.loads(MAP_PATH.read_text(encoding="utf-8"))
        if current.get("version") == want:
            return current
    except Exception:
        pass
    return build()


def query(module: str = "", repo: str = "") -> Dict[str, Any]:
    """A filtered slice of the map: a repo, or modules whose file matches."""
    m = load()
    if repo:
        r = m["repos"].get(repo)
        if not r:
            return {"ok": False, "error": f"unknown repo {repo!r}", "known": sorted(m["repos"])}
        return {"ok": True, "result": {"repo": repo, "modules": r["modules"]}}
    if module:
        needle = module.lower()
        hits = []
        for slug, r in m["repos"].items():
            for mod in r["modules"]:
                if needle in mod.get("file", "").lower():
                    hits.append({"repo": slug, **mod})
        return {"ok": True, "result": {"matches": hits}}
    # No filter: the module list only, not their contents.
    index = {slug: [mod.get("file") for mod in r["modules"]] for slug, r in m["repos"].items()}
    return {"ok": True, "result": {"version": m["version"], "index": index}}


def search(symbol: str) -> Dict[str, Any]:
    """Where a symbol is defined: Python functions/classes, TS exports."""
    m = load()
    needle = (symbol or "").strip()
    if not needle:
        return {"ok": False, "error": "symbol required"}
    hits = []
    for slug, r in m["repos"].items():
        for mod in r["modules"]:
            if needle in (mod.get("functions") or []) or needle in (mod.get("classes") or []) \
               or needle in (mod.get("exports") or []):
                hits.append({"repo": slug, "file": mod.get("file")})
    return {"ok": True, "result": {"symbol": needle, "defined_in": hits}}
